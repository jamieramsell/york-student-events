package york.studentevents.events;

/** Categories available for classifying student events on the York Student Events platform. */
public enum EventCategory {

    /** Lectures, workshops, seminars, and study sessions. */
    ACADEMIC,

    /** Casual social gatherings, mixers, and meetups. */
    SOCIAL,

    /** Sporting fixtures, training sessions, and fitness classes. */
    SPORTS,

    /** Performances, exhibitions, theatre, and film screenings. */
    ARTS_AND_CULTURE,

    /** Concerts, open mic nights, and DJ events. */
    MUSIC,

    /** Careers fairs, networking events, and employer talks. */
    CAREERS,

    /** Mental health, meditation, and general wellness events. */
    WELLBEING,

    /** Charity, community, and volunteering opportunities. */
    VOLUNTEERING,

    /** Society-run events that do not fit a more specific category. */
    SOCIETIES,

    /** Pub crawls, food markets, bake sales, and dining events. */
    FOOD_AND_DRINK,

    /** Charity fundraisers and sponsored events. */
    FUNDRAISER,

    /** Freshers' Week events and welcome activities for new students. */
    FRESHERS,

    /** Club nights, bar events, and late-night social events. */
    NIGHTLIFE
}
